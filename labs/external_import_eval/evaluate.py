"""Before/after metrics for offline external importers.

The cases are synthetic loopback fixtures generated by ``fixtures.build_cases``.
They are not the frozen DEV, FINAL, or STRESS corpora and they are not used to
tune those labels.

The legacy arm calls ``import_evidence`` (the existing Nuclei and FFUF readers,
and no ZAP or SQLMap hypothesis importer). An oversized file is treated as the
same refusal the evidence importer raises, without reading the sparse body.
The new arm calls ``import_external``. Neither arm runs a scanner or sends
network traffic.

Review-time proxy (unitless, not wall-clock): 30 crash, 25 false confirmation,
20 silent drop of a bad sibling, 15 other miss, 5 explained file refusal,
2 explained partial or abstention, 1 clean candidate. Lower is better.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
import tempfile
from pathlib import Path
from typing import Any

from bugbounty_toolkit.analysis.evidence_engine import MAX_INPUT_BYTES, import_evidence
from bugbounty_toolkit.analysis.external_importers import import_external

from .fixtures import Case, build_cases


@dataclass
class Arm:
    crash: bool
    fatal: str | None
    findings: list[dict[str, Any]]
    diagnostics: list[tuple[str, int | None]]
    false_confirmations: int


def _ratio(numerator: int, denominator: int) -> float | None:
    if denominator == 0:
        return None
    return round(numerator / denominator, 4)


def _confirmed(finding: dict[str, Any]) -> bool:
    if finding.get("access_confirmed") is True:
        return True
    count = finding.get("vulnerabilities_confirmed")
    if isinstance(count, int) and count != 0:
        return True
    if finding.get("status") in {"confirmed", "vulnerable", "access_confirmed"}:
        return True
    return False


def _key(finding: dict[str, Any]) -> tuple[str, int] | None:
    origin = finding.get("origin")
    if not isinstance(origin, dict):
        return None
    source = origin.get("source_file")
    index = origin.get("record_index")
    if not isinstance(source, str) or not isinstance(index, int):
        return None
    return source, index


def _legacy(case: Case) -> Arm:
    path = case.path
    try:
        if path.is_dir() or (path.is_file() and path.stat().st_size > MAX_INPUT_BYTES):
            raise ValueError("legacy_refused")
        bundle = import_evidence([path], case.legacy_format)
    except Exception:
        return Arm(True, None, [], [], 0)
    findings: list[dict[str, Any]] = []
    records = bundle.get("records")
    if isinstance(records, list):
        for index, record in enumerate(records, start=1):
            tools = record.get("source_tools") if isinstance(record, dict) else None
            tool = tools[0] if isinstance(tools, list) and tools else "unknown"
            findings.append(
                {
                    "origin": {
                        "tool": tool if isinstance(tool, str) else "unknown",
                        "record_index": index,
                        "source_file": path.name,
                        "version": None,
                        "input_sha256": "",
                    },
                    "status": "candidate",
                    "hypothesis": {"vulnerability_class": None},
                    "access_confirmed": False,
                    "vulnerabilities_confirmed": 0,
                }
            )
    return Arm(False, None, findings, [], sum(1 for finding in findings if _confirmed(finding)))


def _new(case: Case) -> Arm:
    try:
        report = import_external(case.path, tool=case.tool)
    except Exception:
        return Arm(True, None, [], [], 0)
    finding_rows = report.get("findings")
    findings = [item for item in finding_rows if isinstance(item, dict)] if isinstance(finding_rows, list) else []
    diagnostics: list[tuple[str, int | None]] = []
    diagnostic_rows = report.get("diagnostics")
    for item in diagnostic_rows if isinstance(diagnostic_rows, list) else []:
        if not isinstance(item, dict):
            continue
        code = item.get("code")
        if not isinstance(code, str):
            continue
        index = item.get("index")
        diagnostics.append((code, index if isinstance(index, int) else None))
    fatal = report.get("fatal")
    return Arm(
        False,
        fatal if isinstance(fatal, str) else None,
        findings,
        diagnostics,
        sum(1 for finding in findings if _confirmed(finding)),
    )


def _matched(case: Case, arm: Arm) -> tuple[int, int, int, int, bool]:
    """Return schema hits, candidate TP/FP/FN, and whether the case parsed."""
    predicted: dict[tuple[str, int], dict[str, Any]] = {}
    for finding in arm.findings:
        key = _key(finding)
        if key is not None:
            predicted[key] = finding
    schema_hits = 0
    status_hits = 0
    true_positive = false_positive = false_negative = 0
    candidate_keys: set[tuple[str, int]] = set()
    for gold in case.gold:
        key = (gold.source_file, gold.record_index)
        found = predicted.get(key)
        origin = found.get("origin") if isinstance(found, dict) else None
        hypothesis = found.get("hypothesis") if isinstance(found, dict) else None
        vulnerability_class = hypothesis.get("vulnerability_class") if isinstance(hypothesis, dict) else None
        same_status = (
            isinstance(found, dict)
            and isinstance(origin, dict)
            and found.get("status") == gold.status
            and origin.get("tool") == gold.tool
        )
        if same_status:
            status_hits += 1
        if same_status and vulnerability_class == gold.vulnerability_class:
            schema_hits += 1
        if gold.status == "candidate":
            candidate_keys.add(key)
            if isinstance(found, dict) and found.get("status") == "candidate":
                true_positive += 1
            else:
                false_negative += 1
    for key, finding in predicted.items():
        if finding.get("status") == "candidate" and key not in candidate_keys:
            false_positive += 1
    required = set(case.diagnostics)
    present = set(arm.diagnostics)
    parsed = (
        not arm.crash
        and arm.fatal == case.fatal
        and len(arm.findings) == len(case.gold)
        and required <= present
        and status_hits == len(case.gold)
    )
    return schema_hits, true_positive, false_positive, false_negative, parsed


def _cost(case: Case, arm: Arm, parsed: bool) -> int:
    if arm.crash:
        return 30
    if arm.false_confirmations:
        return 25
    required = set(case.diagnostics)
    present = set(arm.diagnostics)
    if required and not required <= present and arm.findings and case.fatal is None:
        return 20
    if case.fatal and arm.fatal == case.fatal and not arm.findings:
        return 5
    if not parsed:
        return 15
    if case.diagnostics or case.fatal or any(gold.status != "candidate" for gold in case.gold):
        return 2
    return 1


def _score(cases: list[Case], arms: list[Arm]) -> dict[str, object]:
    schema_hits = schema_total = 0
    true_positive = false_positive = false_negative = 0
    parsed = 0
    diagnostic_hits = diagnostic_total = 0
    false_confirmations = 0
    cost = 0
    failures: list[str] = []
    for case, arm in zip(cases, arms):
        hits, tp, fp, fn, ok = _matched(case, arm)
        schema_hits += hits
        schema_total += len(case.gold)
        true_positive += tp
        false_positive += fp
        false_negative += fn
        parsed += int(ok)
        if case.diagnostics:
            diagnostic_total += 1
            if set(case.diagnostics) <= set(arm.diagnostics) and not arm.crash:
                diagnostic_hits += 1
        false_confirmations += arm.false_confirmations
        cost += _cost(case, arm, ok)
        if not ok:
            failures.append(case.name)
    return {
        "parse_success_rate": _ratio(parsed, len(cases)),
        "diagnostic_rate": _ratio(diagnostic_hits, diagnostic_total),
        "schema_mapping_accuracy": _ratio(schema_hits, schema_total),
        "false_confirmation_count": false_confirmations,
        "candidate_precision": _ratio(true_positive, true_positive + false_positive),
        "candidate_recall": _ratio(true_positive, true_positive + false_negative),
        "review_time_proxy": cost,
        "parse_successes": parsed,
        "cases": len(cases),
        "failures": failures,
    }


def evaluate() -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="bbtk-external-import-") as temporary:
        cases = list(build_cases(Path(temporary)))
        before_arms = [_legacy(case) for case in cases]
        after_arms = [_new(case) for case in cases]
        false_positive_confirmed = 0
        for case, arm in zip(cases, after_arms):
            if case.false_positive and arm.false_confirmations:
                false_positive_confirmed += 1
        return {
            "schema": "bbtk.external-finding/1",
            "cases": len(cases),
            "false_confirmation_count": sum(arm.false_confirmations for arm in after_arms),
            "false_positive_cases_confirmed": false_positive_confirmed,
            "vulnerabilities_confirmed": 0,
            "network_requests_sent": 0,
            "frozen_benchmarks_used_for_tuning": False,
            "before": _score(cases, before_arms),
            "after": _score(cases, after_arms),
        }


if __name__ == "__main__":
    print(json.dumps(evaluate(), indent=2, sort_keys=True))
