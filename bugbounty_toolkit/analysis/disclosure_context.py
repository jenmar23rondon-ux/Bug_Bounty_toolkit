"""Exposure model for information-disclosure candidates (context quality v2).

v1 (:func:`bugbounty_toolkit.analysis.information_disclosure.assess_disclosure`)
answers whether a stored body contains a sensitive *shape*. This module answers
a different question: is there evidence the data should not have been available
to the audience that received it?

A candidate is ``reviewable`` only when that audience mismatch is supported.
Otherwise the result is ``inconclusive`` or ``not_a_disclosure``. Nothing in
this module sets ``finding_confirmed`` to true, validates a live credential,
opens a socket, or writes the Evidence Ledger.

Access context is delegated to
:func:`bugbounty_toolkit.analysis.disclosure_access_correlation.correlate_disclosure_access`
and, when the caller supplies already-redacted session observations, to
:func:`bugbounty_toolkit.analysis.actor_provenance.classify_session_controls`.
Those helpers are not reimplemented here.
"""

from __future__ import annotations

from dataclasses import dataclass, field
import json
import re
import time
from typing import Any, Mapping, Sequence

from bugbounty_toolkit.analysis.actor_provenance import classify_session_controls
from bugbounty_toolkit.analysis.disclosure_access_correlation import correlate_disclosure_access
from bugbounty_toolkit.analysis.information_disclosure import (
    DisclosureAssessment,
    Indicator,
    _DOC_PATH,
    _SECRET_CATEGORIES,
    _decode_body,
    assess_disclosure,
)

ANALYSIS_VERSION = "disclosure-context-quality-v2"

DISPOSITIONS = (
    "reviewable",
    "inconclusive",
    "not_a_disclosure",
    "invalid_evidence",
)
EXPOSURE_DIMENSIONS = (
    "sensitive_shape",
    "content_origin",
    "observed_audience",
    "intended_audience",
    "access_auth_state",
    "integrity",
    "completeness",
    "confidence_basis",
    "human_verification_required",
)
HARD_NEGATIVE_ORIGINS = frozenset(
    {
        "documentation",
        "public_certificate",
        "own_user_profile",
        "request_echo",
        "html_comment_public",
        "public_metadata",
        "example_credential",
        "non_secret_text",
    }
)
_INCONCLUSIVE_ORIGINS = frozenset({"prompt_injection_comment", "user_comment"})
_PROMOTING_CORRELATION = frozenset({"ready_for_manual_review", "correlation_candidate"})
_BLOCKING_CORRELATION = frozenset({"reflected_or_example", "fake_or_invalid_credential_shape", "denied_correctly"})
_STRONG_RULES = frozenset(
    {
        "pem_private_key",
        "jwt_shape",
        "synthetic_canary",
        "vendor_key_shape",
        "dotenv_secret_assignment",
        "sensitive_key_value",
        "url_embedded_credentials",
        "ssn_shape",
    }
)
# Shapes that stay reviewable even when the only copy sits in a user-comment field.
# Canaries and JWTs in a comment are user content unless a stronger shape is present.
_COMMENT_KEEP_RULES = frozenset(
    {
        "pem_private_key",
        "vendor_key_shape",
        "dotenv_secret_assignment",
        "url_embedded_credentials",
        "ssn_shape",
    }
)
_META_KEYS = frozenset({"version", "name", "support", "service", "status", "ok", "build", "environment", "app"})
_COMMENT_KEY = re.compile(r"(?i)^(comments?|user_comments?|html_comments?|messages?)$")
_EXAMPLE_KEY = re.compile(
    r"(?i)(?:^example$|^sample$|^dummy$|^placeholder$|^examples$)|(?:^|[_\-])(?:example|sample|dummy|placeholder)(?:$|[_\-]|$)"
)
_EXAMPLE_MARK = re.compile(r"(?i)\b(?:example|sample|dummy|placeholder|for demonstration|do not use)\b")
_PROMPT = re.compile(r"(?i)ignore\s+(?:all\s+)?previous|system\s*:|finding_confirmed\s*=\s*true|\byou are now\b")
_HTML_COMMENT = re.compile(r"<!--([\s\S]{0,20000}?)-->")
_PUBLIC_COMMENT = re.compile(
    r"(?i)\b(?:copyright|all rights reserved|public note|this is public|licensed under|license|generated by|build id)\b"
)
_STRONG_INLINE = re.compile(
    r"(?im)-----BEGIN (?:RSA |EC |DSA |OPENSSH |ENCRYPTED )?PRIVATE KEY-----"
    r"|^\s*(?:export\s+)?[A-Z0-9_]*(?:PASSWORD|PASSWD|SECRET|TOKEN|API_?KEY|PRIVATE|CREDENTIAL)[A-Z0-9_]*\s*="
    r"|sk_live_[A-Za-z0-9]{16,}"
    r"|gh[pousr]_[A-Za-z0-9]{20,}"
)
_STRONG_PII_SUFFIX = re.compile(
    r"(?i)(?:^|\.)(?:ssn|social_security_number|national_id|passport|credit_card|card_number|iban)$"
)
_PROFILE_URL = re.compile(r"(?i)/(?:me|profile|account|users/self)(?:/|$|\?)")
_MAX_DEPTH = 32


@dataclass
class ContextAssessment:
    """One minimized exposure decision. Never contains secret values."""

    response_id: str
    disposition: str
    high_confidence: bool
    audience_mismatch: bool
    v1_state: str
    categories: list[str]
    exposure: dict[str, Any]
    body_sha256: str | None
    correlation_state: str | None = None
    elapsed_ms: float = 0.0
    finding_confirmed: bool = False
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        high = bool(self.high_confidence) and self.disposition == "reviewable"
        mismatch = self.disposition == "reviewable"
        exposure = dict(self.exposure)
        exposure["human_verification_required"] = self.disposition in {"reviewable", "inconclusive"}
        return {
            "analysis_version": ANALYSIS_VERSION,
            "response_id": self.response_id,
            "disposition": self.disposition,
            "high_confidence": high,
            "confidence": _confidence_band(high, self.disposition),
            "audience_mismatch": mismatch,
            "finding_confirmed": False,
            "v1_state": self.v1_state,
            "categories": list(self.categories),
            "exposure": exposure,
            "correlation_state": self.correlation_state,
            "body_sha256": self.body_sha256,
            "elapsed_ms": self.elapsed_ms,
            "secret_values_included": False,
            "network_requests_sent": 0,
            "ledger_mutated": False,
            "notes": list(self.notes),
        }


def provenance_complete(exposure: Mapping[str, Any]) -> bool:
    """True when every exposure dimension is present and non-empty."""
    if any(name not in exposure for name in EXPOSURE_DIMENSIONS):
        return False
    basis = exposure.get("confidence_basis")
    if not isinstance(basis, list) or not basis or not all(isinstance(item, str) and item for item in basis):
        return False
    if not isinstance(exposure.get("human_verification_required"), bool):
        return False
    for name in EXPOSURE_DIMENSIONS:
        if name in {"confidence_basis", "human_verification_required"}:
            continue
        value = exposure.get(name)
        if not isinstance(value, str) or not value:
            return False
    return True


def _confidence_band(high: bool, disposition: str) -> str:
    if high:
        return "high"
    if disposition == "reviewable":
        return "medium"
    if disposition == "inconclusive":
        return "low"
    return "none"


def _matches(indicators: list[Indicator], rules: frozenset[str]) -> bool:
    for item in indicators:
        if item.rule in rules:
            return True
        if item.rule == "pii_field" and _STRONG_PII_SUFFIX.search(item.location):
            return True
    return False


def _strong(indicators: list[Indicator]) -> bool:
    return _matches(indicators, _STRONG_RULES)


def _shape(primary: DisclosureAssessment) -> str:
    categories = set(primary.categories)
    if categories & set(_SECRET_CATEGORIES):
        return "secret"
    if categories:
        return "sensitive_context"
    if "public_key_material_only" in primary.reasons:
        return "public_material"
    if primary.suppressed:
        return "suppressed_only"
    return "none"


def _headers(response: Mapping[str, Any]) -> dict[str, str]:
    raw = response.get("headers") or {}
    if not isinstance(raw, Mapping):
        return {}
    return {str(key): str(value) for key, value in raw.items()}


def _content_type(headers: Mapping[str, str]) -> str:
    for key, value in headers.items():
        if key.lower() == "content-type":
            return value.lower()
    return ""


def _rescan(record: Mapping[str, Any], text: str, salt: str) -> DisclosureAssessment:
    response = dict(record.get("response") or {})
    headers = {key: value for key, value in _headers(response).items() if key.lower() != "content-encoding"}
    response["headers"] = headers
    response["body"] = text
    cloned: dict[str, Any] = {
        "id": record.get("id", "response"),
        "audience": record.get("audience", "unknown"),
        "url": record.get("url", ""),
        "request": record.get("request") if isinstance(record.get("request"), Mapping) else {},
        "response": response,
    }
    return assess_disclosure(cloned, salt=salt)


def _json_or_none(text: str) -> Any:
    try:
        return json.loads(text)
    except ValueError:
        return None


def _dump_transformed(text: str, transform: Any) -> str | None:
    parsed = _json_or_none(text)
    if parsed is None:
        return None
    return json.dumps(transform(parsed))


def _blank_example(parsed: Any) -> Any:
    def transform(key: str, child: Any, depth: int) -> Any:
        if _EXAMPLE_KEY.search(key):
            return "" if not isinstance(child, (dict, list)) else _blank_all(child, depth + 1)
        return _walk_example(child, depth + 1)

    def _walk_example(value: Any, depth: int) -> Any:
        if depth > _MAX_DEPTH:
            return value
        if isinstance(value, dict):
            return {str(key): transform(str(key), child, depth) for key, child in value.items()}
        if isinstance(value, list):
            return [_walk_example(child, depth + 1) for child in value[:1000]]
        return value

    def _blank_all(value: Any, depth: int) -> Any:
        if depth > _MAX_DEPTH:
            return ""
        if isinstance(value, dict):
            return {str(key): _blank_all(child, depth + 1) for key, child in value.items()}
        if isinstance(value, list):
            return [_blank_all(child, depth + 1) for child in value[:1000]]
        return ""

    return _walk_example(parsed, 0)


def _blank_comment_keys(parsed: Any) -> Any:
    def visit(value: Any, depth: int) -> Any:
        if depth > _MAX_DEPTH:
            return value
        if isinstance(value, dict):
            out: dict[str, Any] = {}
            for key, child in value.items():
                name = str(key)
                if _COMMENT_KEY.match(name) and isinstance(child, str):
                    out[name] = ""
                else:
                    out[name] = visit(child, depth + 1)
            return out
        if isinstance(value, list):
            return [visit(child, depth + 1) for child in value[:1000]]
        return value

    return visit(parsed, 0)


def _blank_prompt_strings(parsed: Any) -> Any:
    def visit(value: Any, depth: int) -> Any:
        if depth > _MAX_DEPTH:
            return value
        if isinstance(value, dict):
            return {str(key): visit(child, depth + 1) for key, child in value.items()}
        if isinstance(value, list):
            return [visit(child, depth + 1) for child in value[:1000]]
        if isinstance(value, str) and _PROMPT.search(value):
            return ""
        return value

    return visit(parsed, 0)


def _blank_example_lines(text: str) -> str:
    kept: list[str] = []
    for line in text.splitlines(keepends=True):
        if _EXAMPLE_MARK.search(line):
            kept.append("\n" if line.endswith("\n") else "")
        else:
            kept.append(line)
    return "".join(kept)


def _blank_public_html_comments(text: str) -> str:
    def repl(match: re.Match[str]) -> str:
        body = match.group(1)
        if _STRONG_INLINE.search(body):
            return match.group(0)
        if _PUBLIC_COMMENT.search(body) or _EXAMPLE_MARK.search(body):
            return ""
        return match.group(0)

    return _HTML_COMMENT.sub(repl, text)


def _neutralize_prompt_text(text: str) -> str:
    parsed = _json_or_none(text)
    if isinstance(parsed, (dict, list)):
        dumped = json.dumps(_blank_prompt_strings(parsed))
    else:
        dumped = text
    dumped = _HTML_COMMENT.sub(lambda match: "" if _PROMPT.search(match.group(1)) else match.group(0), dumped)
    if _PROMPT.search(text) and not isinstance(parsed, (dict, list)) and _PROMPT.search(dumped):
        # A non-JSON body that is itself the injection is not a secret store.
        if _PROMPT.search(text) and len(text) <= 20000:
            return ""
    return dumped


def _lost_all(before: DisclosureAssessment, after: DisclosureAssessment) -> bool:
    return bool(before.categories) and not after.categories


def _is_meta(text: str) -> bool:
    parsed = _json_or_none(text)
    if not isinstance(parsed, dict) or not parsed:
        return False
    return all(str(key).lower() in _META_KEYS for key in parsed)


def _intended(origin: str, shape: str, categories: set[str], strong: bool) -> str:
    if origin in {"documentation", "public_certificate", "public_metadata", "html_comment_public"}:
        return "public"
    if origin in {"example_credential", "non_secret_text"}:
        return "example_only"
    if origin == "own_user_profile":
        return "authenticated_owner"
    if origin == "server_emitted" and shape in {"secret", "sensitive_context"}:
        if categories == {"pii"} and not strong:
            return "unknown"
        return "restricted"
    return "unknown"


def _classify_origin(
    record: Mapping[str, Any],
    primary: DisclosureAssessment,
    text: str,
    *,
    salt: str,
    audience: str,
    url: str,
) -> str:
    categories = set(primary.categories)
    if _DOC_PATH.search(url) or (not categories and "documentation_examples_only" in primary.reasons):
        return "documentation"
    if not categories and any(item.suppressed_reason == "reflected_from_request" for item in primary.suppressed):
        return "request_echo"
    if not categories and "public_key_material_only" in primary.reasons:
        return "public_certificate"
    if not categories and primary.suppressed:
        reasons = {item.suppressed_reason for item in primary.suppressed}
        if reasons <= {"placeholder_value", "documentation_example"}:
            return "example_credential"
        if reasons <= {"placeholder_value", "documentation_example", "descriptive_text_not_secret"}:
            return "non_secret_text"

    example_text = text
    dumped_example = _dump_transformed(text, _blank_example)
    if dumped_example is not None:
        example_text = dumped_example
    elif "json" not in _content_type(_headers(record.get("response") or {})):
        example_text = _blank_example_lines(text)
    if categories and _lost_all(primary, _rescan(record, example_text, salt)):
        return "example_credential"
    if categories and _PROMPT.search(text) and _lost_all(primary, _rescan(record, _neutralize_prompt_text(text), salt)):
        return "prompt_injection_comment"
    if categories and _lost_all(primary, _rescan(record, _blank_public_html_comments(text), salt)):
        return "html_comment_public"
    dumped_comments = _dump_transformed(text, _blank_comment_keys)
    if (
        categories
        and dumped_comments is not None
        and _lost_all(primary, _rescan(record, dumped_comments, salt))
        and not _matches(primary.indicators, _COMMENT_KEEP_RULES)
    ):
        return "user_comment"
    profile = bool(_PROFILE_URL.search(url))
    if audience == "authenticated_self" and categories <= {"pii"} and (categories or profile):
        return "own_user_profile"
    if not categories and _HTML_COMMENT.search(text) and (_PUBLIC_COMMENT.search(text) or _EXAMPLE_MARK.search(text)):
        return "html_comment_public"
    if not categories and _is_meta(text):
        return "public_metadata"
    if categories:
        return "server_emitted"
    return "unknown"


def _session_blocks(observations: Any) -> tuple[bool, str | None]:
    if not isinstance(observations, list) or not observations:
        return False, None
    rows = [dict(item) for item in observations if isinstance(item, Mapping)]
    if not rows:
        return False, None
    summary = classify_session_controls(rows)
    raw_sessions = summary.get("sessions")
    sessions: dict[str, Any] = raw_sessions if isinstance(raw_sessions, dict) else {}
    labels = sorted(
        {
            str(row.get("classification"))
            for row in sessions.values()
            if isinstance(row, Mapping) and row.get("classification")
        }
    )
    blocked = any(
        isinstance(item, Mapping) and item.get("result") == "inconclusive"
        for item in summary.get("dependent_results") or []
    )
    auth = "session:" + ",".join(labels) if labels else "session:unclassified"
    return blocked, auth


def _correlate(access_case: Any, salt: str) -> tuple[str | None, list[str]]:
    if access_case is None:
        return None, []
    if not isinstance(access_case, Mapping):
        return "invalid_evidence", ["access_case_not_object"]
    try:
        result = correlate_disclosure_access(access_case, salt=salt)
    except (TypeError, ValueError):
        return "invalid_evidence", ["access_case_rejected"]
    return result.state, [f"correlation:{code}" for code in result.reasons[:8]]


def _invalid(
    response_id: str, reason: str, *, v1_state: str = "invalid_evidence", sha: str | None = None, elapsed: float = 0.0
) -> ContextAssessment:
    exposure = {
        "sensitive_shape": "none",
        "content_origin": "unknown",
        "observed_audience": "unknown",
        "intended_audience": "unknown",
        "access_auth_state": "undeclared",
        "integrity": "invalid_evidence",
        "completeness": "missing",
        "confidence_basis": [reason, f"v1:{v1_state}"],
        "human_verification_required": False,
    }
    return ContextAssessment(
        response_id=response_id,
        disposition="invalid_evidence",
        high_confidence=False,
        audience_mismatch=False,
        v1_state=v1_state,
        categories=[],
        exposure=exposure,
        body_sha256=sha,
        elapsed_ms=elapsed,
        notes=[reason],
    )


def assess_context(record: Mapping[str, Any], *, salt: str = "") -> ContextAssessment:
    """Score one stored response. Offline, minimized, never confirmed."""
    started = time.perf_counter()
    response_id = str(record.get("id", "response"))[:128] if isinstance(record, Mapping) else "response"

    def elapsed() -> float:
        return round((time.perf_counter() - started) * 1000, 3)

    if not isinstance(record, Mapping):
        return _invalid(response_id, "record_not_object", elapsed=elapsed())
    primary = assess_disclosure(record, salt=salt)
    if primary.state == "invalid_evidence":
        return _invalid(
            response_id,
            primary.reasons[0] if primary.reasons else "invalid_evidence",
            v1_state=primary.state,
            sha=primary.body_sha256,
            elapsed=elapsed(),
        )

    raw_response = record.get("response")
    response: Mapping[str, Any] = raw_response if isinstance(raw_response, Mapping) else {}
    headers = _headers(response)
    text, error = _decode_body(headers, response.get("body"))
    if text is None:
        return _invalid(
            response_id,
            error or "invalid_body",
            v1_state="invalid_evidence",
            sha=primary.body_sha256,
            elapsed=elapsed(),
        )

    audience = primary.audience
    url = str(record.get("url", ""))
    origin = _classify_origin(record, primary, text, salt=salt, audience=audience, url=url)
    categories = list(primary.categories)
    category_set = set(categories)
    strong = _strong(primary.indicators)
    shape = _shape(primary)
    truncated = bool(response.get("truncated"))
    integrity = "truncated" if truncated else "valid"
    completeness = "partial" if truncated else "complete"
    correlation_state, correlation_notes = _correlate(record.get("access_case"), salt or response_id)
    session_blocked, session_auth = _session_blocks(record.get("session_observations"))

    if correlation_state == "integrity_blocked":
        integrity = "integrity_blocked"

    if audience == "public":
        access_auth = "unauthenticated"
    elif audience == "authenticated_self":
        access_auth = "authenticated_owner"
    elif audience == "cross_actor":
        access_auth = "cross_actor_unproven"
    else:
        access_auth = "undeclared"
    if correlation_state:
        access_auth = f"correlation:{correlation_state}"
    if session_auth:
        access_auth = f"{access_auth}|{session_auth}"

    basis: list[str] = [f"origin:{origin}", f"v1:{primary.state}"]
    basis.extend(correlation_notes)
    hard = origin in HARD_NEGATIVE_ORIGINS
    can_review = (
        integrity == "valid" and completeness == "complete" and audience not in {"unknown", "authenticated_self"}
    )

    if hard:
        disposition = "not_a_disclosure"
        basis.append("hard_negative")
    elif origin in _INCONCLUSIVE_ORIGINS:
        disposition = "inconclusive"
        basis.append("content_origin_not_audience_mismatch")
    elif not category_set:
        disposition = "not_a_disclosure"
        basis.append("no_sensitive_indicator")
    elif not can_review:
        disposition = "inconclusive"
        if truncated:
            basis.append("truncated_body")
        elif audience == "unknown":
            basis.append("audience_unknown")
        elif audience == "authenticated_self":
            basis.append("owner_session_not_mismatch")
        elif integrity != "valid":
            basis.append("integrity_not_valid")
    elif audience == "public" and category_set == {"pii"} and not strong:
        disposition = "inconclusive"
        basis.append("public_profile_pii_not_mismatch")
    elif audience == "public" and origin == "server_emitted":
        disposition = "reviewable"
        basis.append("public_audience_mismatch")
    elif audience == "cross_actor" and origin == "server_emitted" and correlation_state in _PROMOTING_CORRELATION:
        disposition = "reviewable"
        basis.append("correlation_audience_mismatch")
    else:
        disposition = "inconclusive"
        basis.append("no_audience_mismatch")

    if correlation_state == "integrity_blocked":
        disposition = "inconclusive" if category_set else "not_a_disclosure"
        basis.append("correlation_blocks_review")
    elif correlation_state in _BLOCKING_CORRELATION:
        # Reflected, fake, or correctly denied evidence must not become a reviewable disclosure.
        if category_set and origin == "server_emitted" and correlation_state != "denied_correctly":
            disposition = "inconclusive"
        else:
            disposition = "not_a_disclosure"
        basis.append("correlation_blocks_review")
    elif audience == "cross_actor" and correlation_state not in _PROMOTING_CORRELATION and disposition == "reviewable":
        disposition = "inconclusive"
        basis.append("correlation_does_not_show_mismatch")

    if session_blocked and audience == "cross_actor" and disposition == "reviewable":
        disposition = "inconclusive"
        basis.append("session_control_inconclusive")

    if integrity != "valid" and disposition == "reviewable":
        disposition = "inconclusive"
        basis.append("integrity_blocks_review")

    if primary.state == "ready_for_manual_review" and disposition != "reviewable":
        basis.append("demoted_from_v1_ready_for_manual_review")
    if primary.state == "access_control_validation_required" and disposition != "reviewable":
        basis.append("demoted_from_v1_access_control_validation_required")

    high = (
        disposition == "reviewable"
        and origin == "server_emitted"
        and strong
        and audience in {"public", "cross_actor"}
        and (audience != "cross_actor" or correlation_state == "ready_for_manual_review")
    )
    if record.get("finding_confirmed") is True:
        basis.append("input_claimed_confirmed_ignored")

    exposure = {
        "sensitive_shape": shape,
        "content_origin": origin,
        "observed_audience": audience,
        "intended_audience": _intended(origin, shape, category_set, strong),
        "access_auth_state": access_auth,
        "integrity": integrity,
        "completeness": completeness,
        "confidence_basis": basis,
        "human_verification_required": disposition in {"reviewable", "inconclusive"},
    }
    return ContextAssessment(
        response_id=response_id,
        disposition=disposition,
        high_confidence=high,
        audience_mismatch=disposition == "reviewable",
        v1_state=primary.state,
        categories=sorted(category_set),
        exposure=exposure,
        body_sha256=primary.body_sha256,
        correlation_state=correlation_state,
        elapsed_ms=elapsed(),
        notes=["Exposure model does not validate credentials or confirm a finding."],
    )


def assess_context_batch(records: Sequence[Mapping[str, Any]], *, salt: str = "") -> dict[str, Any]:
    """Assess many stored records. Shareable summary; no secret values."""
    if isinstance(records, (str, bytes)) or not isinstance(records, Sequence):
        raise ValueError("Disclosure context input must contain a list of records.")
    results = [
        assess_context(item, salt=salt).to_dict()
        if isinstance(item, Mapping)
        else _invalid(f"record-{index}", "record_not_object").to_dict()
        for index, item in enumerate(records)
    ]
